#!/usr/bin/env bash
# Prepare Tier 1 host-side lab runtime: tunnel, cookie, env, redline.json.
# Does not start or stop lab VMs. Opt-in operator tool only.
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"

usage() {
  cat <<'EOF'
usage: prepare.sh --vm umbrel|ubuntu|startos [options]

Prepare a host-side runtime for Tier 1 live smoke and manual scans against
bitcoin-vm-lab. Does not manage VM lifecycle.

options:
  --vm NAME              umbrel, ubuntu, or startos
  --electrum KIND        electrs (default), fulcrum, or none
  --runtime-dir PATH     default: .lab/runtime/<vm>
  --skip-cookie-fetch    reuse existing runtime cookie file
  --no-tunnel            do not auto-start SSH tunnel
  -h, --help             show this help

Platform notes:
  umbrel   Tunnel RPC to guest loopback (LAN :9332 is 403). Electrum on guest IP.
  ubuntu   Tunnel RPC + Electrum (guest loopback only). Needs SSH private key.
  startos  Tunnel RPC/Electrum into package LXCs; cookie via sudo cat.

environment:
  BITCOIN_VM_LAB, REDLINE_LAB_IP, REDLINE_LAB_RPC_ENDPOINT,
  REDLINE_LAB_ELECTRUM_ENDPOINT, REDLINE_LAB_COOKIE_REMOTE,
  UMBREL_SSH_PRIVATE_KEY, UBUNTU_SSH_PRIVATE_KEY / UBUNTU_CLOUD_SSH_KEY,
  STARTOS_SSH_PRIVATE_KEY

outputs under runtime dir:
  cookie, fs-probe/, redline.json, env, meta.json
EOF
}

VM=""
ELECTRUM=electrs
RUNTIME=""
SKIP_COOKIE=0
AUTO_TUNNEL=1

while [[ $# -gt 0 ]]; do
  case "$1" in
    --vm)
      VM="${2:-}"
      shift 2
      ;;
    --electrum)
      ELECTRUM="${2:-}"
      shift 2
      ;;
    --runtime-dir)
      RUNTIME="${2:-}"
      shift 2
      ;;
    --skip-cookie-fetch)
      SKIP_COOKIE=1
      shift
      ;;
    --no-tunnel)
      AUTO_TUNNEL=0
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      die "unknown argument: $1"
      ;;
  esac
done

[[ -n "$VM" ]] || die "--vm is required (see --help)"
lab_validate_vm "$VM"
case "$ELECTRUM" in
  electrs|fulcrum|none) ;;
  *) die "--electrum must be electrs, fulcrum, or none" ;;
esac

need_cmd ssh
need_cmd python3
need_cmd mkdir
need_cmd chmod
need_cmd install

if [[ -z "$RUNTIME" ]]; then
  RUNTIME="$(lab_runtime_for_vm "$VM")"
fi
if [[ "$RUNTIME" != /* ]]; then
  RUNTIME="$REDLINE_ROOT/$RUNTIME"
fi
mkdir -p "$RUNTIME"
RUNTIME="$(cd "$RUNTIME" && pwd)"
COOKIE_FILE="$RUNTIME/cookie"
FS_PROBE="$RUNTIME/fs-probe"
CONFIG_FILE="$RUNTIME/redline.json"
ENV_FILE="$RUNTIME/env"
META_FILE="$RUNTIME/meta.json"
DB_PATH="$RUNTIME/redline.db"

install -d -m 0700 "$RUNTIME"
install -d -m 0700 "$FS_PROBE"

if [[ "$AUTO_TUNNEL" -eq 1 ]] && lab_needs_rpc_tunnel "$VM"; then
  note "ensuring SSH tunnel for $VM"
  "$SCRIPT_DIR/tunnel.sh" --vm "$VM" --runtime-dir "$RUNTIME" start
fi

if [[ "$SKIP_COOKIE" -eq 1 ]]; then
  [[ -f "$COOKIE_FILE" ]] || die "--skip-cookie-fetch set but $COOKIE_FILE missing"
  note "reusing existing cookie file (contents not logged)"
else
  note "fetching cookie from $VM (value not logged)"
  lab_fetch_cookie "$VM" "$COOKIE_FILE"
fi

rpc="$(lab_rpc_endpoint "$VM")"
electrum_ep="$(lab_electrum_endpoint "$VM" "$ELECTRUM")"
ip_display="${REDLINE_LAB_IP:-}"
if [[ -z "$ip_display" ]]; then
  ip_display="$(lab_guest_ip "$VM" 2>/dev/null || printf 'n/a')"
fi

lab_write_config "$CONFIG_FILE" "$rpc" "$COOKIE_FILE" "$FS_PROBE" "$electrum_ep" "$DB_PATH"
chmod 600 "$CONFIG_FILE"

cat >"$ENV_FILE" <<EOF
# Generated by scripts/lab/prepare.sh — do not commit.
export REDLINE_LAB_VM=$VM
export REDLINE_LAB_RUNTIME=$RUNTIME
export REDLINE_LIVE_TEST=1
export REDLINE_LIVE_RPC_ENDPOINT=$(printf '%q' "$rpc")
export REDLINE_LIVE_COOKIE_FILE=$(printf '%q' "$COOKIE_FILE")
export REDLINE_LIVE_DATA_DIRECTORY=$(printf '%q' "$FS_PROBE")
export REDLINE_RPC_ENDPOINT=$(printf '%q' "$rpc")
export REDLINE_DATA_DIRECTORY=$(printf '%q' "$FS_PROBE")
export REDLINE_DATABASE_PATH=$(printf '%q' "$DB_PATH")
EOF

if [[ -n "$electrum_ep" ]]; then
  cat >>"$ENV_FILE" <<EOF
export REDLINE_LIVE_ELECTRUM_TEST=1
export REDLINE_LIVE_ELECTRUM_ENDPOINT=$(printf '%q' "$electrum_ep")
export REDLINE_ELECTRUM_ENABLED=true
export REDLINE_ELECTRUM_ENDPOINT=$(printf '%q' "$electrum_ep")
export REDLINE_ELECTRUM_BITCOIN_COMPONENT_ID=bitcoin.primary
EOF
else
  cat >>"$ENV_FILE" <<EOF
unset REDLINE_LIVE_ELECTRUM_TEST || true
unset REDLINE_LIVE_ELECTRUM_ENDPOINT || true
export REDLINE_ELECTRUM_ENABLED=false
unset REDLINE_ELECTRUM_ENDPOINT || true
EOF
fi
chmod 600 "$ENV_FILE"

python3 - "$META_FILE" "$VM" "$ip_display" "$rpc" "$electrum_ep" "$COOKIE_FILE" "$FS_PROBE" "$CONFIG_FILE" "$DB_PATH" <<'PY'
import json, sys
out, vm, ip, rpc, electrum, cookie, fs, config, db = sys.argv[1:]
meta = {
    "tier": 1,
    "vm": vm,
    "guest_ip": ip,
    "rpc_endpoint": rpc,
    "electrum_endpoint": electrum or None,
    "cookie_file": cookie,
    "data_directory": fs,
    "config_file": config,
    "database_path": db,
    "notes": [
        "filesystem.capacity describes the host path data_directory, not the guest datadir",
        "cookie file mode should remain 600; never commit runtime dir",
        "live smoke success does not require every finding to be pass",
    ],
}
with open(out, "w", encoding="utf-8") as f:
    json.dump(meta, f, indent=2)
    f.write("\n")
PY
chmod 600 "$META_FILE"

note "runtime ready: $RUNTIME"
note "vm=$VM rpc=$rpc electrum=${electrum_ep:-disabled}"
note "next: ./scripts/lab/smoke.sh --runtime-dir $RUNTIME"
note "source env: set -a; source $ENV_FILE; set +a"
printf '%s\n' "$RUNTIME"
